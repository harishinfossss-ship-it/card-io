def get_deck(concept):
    import urllib.parse
    if concept in db:
        deck = copy.deepcopy(db[concept])
    else:
        deck = copy.deepcopy(db['ben10'])
        
    for card in deck:
        if 'image' in card and 'via.placeholder.com' in card['image']:
            # Genre-specific animated style prompt
            style_map = {
                'ben10': 'Ben 10 animated cartoon series official art style, 2D cel-shaded animation, vibrant neon colors, glowing alien creature, action pose, dark dramatic background',
                'cricket': 'cricket sports anime illustration, dynamic action pose, stadium lights, vibrant colors, 2D animated cel art',
                'avengers': 'Marvel Avengers comic cinematic illustration, dynamic superhero battle pose, vibrant colors, glowing energy',
                'powerrangers': 'Power Rangers super sentai anime illustration, heroic action pose, vivid colors, cel-shaded 2D animation'
            }
            style = style_map.get(concept, '2D animated cartoon illustration, vibrant colors, cel-shaded')
            prompt = f"{card.get('name', 'hero')}, {style}, no text, portrait"
            prompt_encoded = urllib.parse.quote(prompt)
            card['image'] = f"https://image.pollinations.ai/prompt/{prompt_encoded}?width=450&height=650&nologo=true&model=flux"
            
    return deck

